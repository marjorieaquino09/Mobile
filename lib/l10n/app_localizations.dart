  const AppLocalizations(this.locale);

  final Locale locale;

  static const supportedLocales = [Locale('en'), Locale('fil')];
  static const LocalizationsDelegate<AppLocalizations> delegate =
      _AppLocalizationsDelegate();

  static AppLocalizations of(BuildContext context) {
    return Localizations.of<AppLocalizations>(context, AppLocalizations)!;
  }

  String text(String key, {Map<String, String> values = const {}}) {
    var message =
        _values[locale.languageCode]?[key] ?? _values['en']![key] ?? key;
    for (final value in values.entries) {
      message = message.replaceAll('{${value.key}}', value.value);
    }
    return message;
  }

  String languageName(String code) {
    return text(code == 'fil' ? 'languageTagalog' : 'languageEnglish');
  }

  String themeModeName(String mode) {
    switch (mode) {
      case 'light':
        return text('themeLight');
      case 'dark':
        return text('themeDark');
      case 'system':
      default:
        return text('themeSystem');
    }
  }

  /// Localize known product category labels; unknown names returned as-is.
  String category(String name) {
    final key = _categoryKeys[name];
    if (key == null) return name;
    return text(key);
